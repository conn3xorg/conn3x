// Command moddoc writes the module reference for the docs site: one
// Markdown page per circuit step module, generated from the provider's
// schemas so the reference can't drift from the code.
//
//	go run ./internal/conn3x/provider/moddoc <dir>
package main

import (
	"context"
	"embed"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/zclconf/go-cty/cty"

	"github.com/opentofu/opentofu/internal/configs"
	"github.com/opentofu/opentofu/internal/configs/configschema"
	"github.com/opentofu/opentofu/internal/conn3x/provider"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: moddoc <dir>")
		os.Exit(2)
	}
	if err := write(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// pages holds the hand-written part of each module's page; see pages/README.md.
//
//go:embed pages
var pages embed.FS

// referenceMarker separates a hand-written page's introduction from its notes.
const referenceMarker = "<!-- reference -->"

// splice puts a hand-written page around a generated one: the part before
// the marker follows the description, replacing the generated example, and
// the part after it closes the page.
func splice(gen, hand string) string {
	if hand == "" {
		return gen
	}
	intro, notes, _ := strings.Cut(hand, referenceMarker)
	head, rest, ok := strings.Cut(gen, "## Arguments")
	if !ok {
		return gen
	}
	if i := strings.Index(head, "```hcl"); i >= 0 {
		head = strings.TrimRight(head[:i], "\n") + "\n\n"
	}
	out := head + strings.TrimSpace(intro) + "\n\n## Arguments" + rest
	if notes = strings.TrimSpace(notes); notes != "" {
		out = strings.TrimRight(out, "\n") + "\n\n" + notes + "\n"
	}
	return out
}

func write(dir string) error {
	p, err := provider.New()
	if err != nil {
		return err
	}
	schemas := p.GetProviderSchema(context.Background()).ResourceTypes
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, rt := range configs.Conn3xStepModules() {
		schema, ok := schemas[rt]
		if !ok {
			return fmt.Errorf("%s: no schema for %s", name, rt)
		}
		hand, _ := pages.ReadFile("pages/" + name + ".md") // most modules have none yet
		if err := os.WriteFile(filepath.Join(dir, name+".md"), []byte(splice(page(name, rt, schema.Block), string(hand))), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func page(name, rt string, b *configschema.Block) string {
	var args, readOnly []string
	for _, a := range sortedAttrs(b) {
		at := b.Attributes[a]
		if a == "id" {
			continue
		}
		desc := escape(at.Description)
		switch {
		case at.Required:
			args = append(args, fmt.Sprintf("| `%s` | %s | Yes | %s |", a, typeName(at.Type), desc))
		case at.Optional:
			args = append(args, fmt.Sprintf("| `%s` | %s | No | %s |", a, typeName(at.Type), desc))
		default:
			readOnly = append(readOnly, fmt.Sprintf("| `%s` | %s | %s |", a, typeName(at.Type), desc))
		}
	}
	var out strings.Builder
	fmt.Fprintf(&out, "---\ntitle: %s\ndescription: %q\n---\n\n", name, b.Description)
	fmt.Fprintf(&out, "<!-- Generated by go run ./internal/conn3x/provider/moddoc in conn3xorg/conn3x. Don't edit by hand. -->\n\n")
	fmt.Fprintf(&out, "%s\n\n", b.Description)
	var required []string
	for _, a := range sortedAttrs(b) {
		if at := b.Attributes[a]; at.Required || firstOfPair(b, a) {
			required = append(required, fmt.Sprintf("    %s = %s\n", a, placeholder(at.Type)))
		}
	}
	if len(required) > 0 {
		fmt.Fprintf(&out, "```hcl\nstep \"example\" {\n  %s {\n%s  }\n}\n```\n\n", name, strings.Join(required, ""))
	}
	fmt.Fprintf(&out, "## Arguments\n\n| Name | Type | Required | Description |\n| --- | --- | --- | --- |\n%s\n\n", strings.Join(args, "\n"))
	if len(readOnly) > 0 {
		fmt.Fprintf(&out, "## Read-only attributes\n\nConn3x sets these; reference them as `conn3x_%s.<circuit>__<step>[\"<host>\"].<name>`.\n\n| Name | Type | Description |\n| --- | --- | --- |\n%s\n\n", strings.TrimPrefix(rt, "conn3x_"), strings.Join(readOnly, "\n"))
	}
	fmt.Fprintf(&out, "A step lowers to the `%s` resource, one instance per host, and connects with its circuit's `ssh` block.\n", rt)
	return out.String()
}

func sortedAttrs(b *configschema.Block) []string {
	names := make([]string, 0, len(b.Attributes))
	for n := range b.Attributes {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

func typeName(t cty.Type) string {
	switch {
	case t == cty.String:
		return "string"
	case t == cty.Number:
		return "number"
	case t == cty.Bool:
		return "bool"
	case t.IsListType():
		return "list of " + typeName(t.ElementType())
	case t.IsMapType():
		return "map of " + typeName(t.ElementType())
	}
	return t.FriendlyName()
}

func placeholder(t cty.Type) string {
	switch {
	case t == cty.Number:
		return "0"
	case t == cty.Bool:
		return "true"
	case t.IsListType():
		return "[]"
	case t.IsMapType():
		return "{}"
	}
	return `"..."`
}

func escape(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// firstOfPair reports whether attr is the alphabetically first of two
// alternatives, described as "Set this or <other>", so examples set one.
func firstOfPair(b *configschema.Block, attr string) bool {
	m := pairRe.FindStringSubmatch(b.Attributes[attr].Description)
	if m == nil {
		return false
	}
	_, ok := b.Attributes[m[1]]
	return ok && attr < m[1]
}

var pairRe = regexp.MustCompile(`Set this or ([a-z_]+)\b`)
