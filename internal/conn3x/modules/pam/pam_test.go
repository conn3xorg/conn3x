// Files as the distributions ship them: Ubuntu 24.04's common-auth and
// sshd, Rocky Linux 10's sshd and the system-auth authselect writes.
const (
	ubuntuCommonAuth = `#
# /etc/pam.d/common-auth - authentication settings common to all services
#

# here are the per-package modules (the "Primary" block)
auth	[success=1 default=ignore]	pam_unix.so nullok
# here's the fallback if no module succeeds
auth	requisite			pam_deny.so
# prime the stack with a positive return value if there isn't one already;
auth	required			pam_permit.so
# and here are more per-package modules (the "Additional" block)
# end of pam-auth-update config
`
	ubuntuSSHD = `# PAM configuration for the Secure Shell service
@include common-auth
account    required     pam_nologin.so
@include common-account
session [success=ok ignore=ignore module_unknown=ignore default=bad]        pam_selinux.so close
session    optional     pam_mail.so standard noenv # [1]
session    required     pam_env.so # [1]
session    required     pam_env.so user_readenv=1 envfile=/etc/default/locale
@include common-password
`
	rockySSHD = `#%PAM-1.0
auth       substack     password-auth
auth       include      postlogin
account    required     pam_sepermit.so
account    include      password-auth
password   include      password-auth
# pam_selinux.so close should be the first session rule
session    required     pam_selinux.so close
session    optional     pam_keyinit.so force revoke
session    include      password-auth
`
	rockySystemAuth = `# Generated by authselect

auth        required                                     pam_env.so
auth        required                                     pam_faildelay.so delay=2000000
auth        sufficient                                   pam_unix.so nullok
auth        required                                     pam_deny.so

password    sufficient                                   pam_unix.so yescrypt shadow nullok use_authtok
password    required                                     pam_deny.so

-session    optional                                     pam_systemd.so
session     [success=1 default=ignore]                   pam_succeed_if.so service in crond quiet use_uid
session     required                                     pam_unix.so
`
)

func ref(t, c, m string) Ref { return Ref{t, c, m} }

func TestApply(t *testing.T) {
	faillock := ref("auth", "required", "pam_faillock.so")
	for name, tc := range map[string]struct {
		in   string
		rule Rule
		// old and new are a line taken out and one put in its place;
		// both empty means no change.
		old, new string
	}{
		"before a bracketed rule, tabs kept": {
			ubuntuCommonAuth, Rule{Ref: faillock, Arguments: []string{"preauth"}, State: Present, Before: "auth [success=1 default=ignore] pam_unix.so"},
			"auth	[success=1 default=ignore]	pam_unix.so nullok",
			"auth	required	pam_faillock.so preauth\nauth	[success=1 default=ignore]	pam_unix.so nullok",
		},
		"before, bracket spacing differs": {
			ubuntuCommonAuth, Rule{Ref: faillock, State: Present, Before: "auth [success = 1  default=ignore] pam_unix.so"},
			"auth	[success=1 default=ignore]	pam_unix.so nullok",
			"auth	required	pam_faillock.so\nauth	[success=1 default=ignore]	pam_unix.so nullok",
		},
		"after, columns kept": {
			rockySystemAuth, Rule{Ref: ref("auth", "[default=die]", "pam_faillock.so"), Arguments: []string{"authfail"}, State: Present, After: "auth sufficient pam_unix.so"},
			"auth        sufficient                                   pam_unix.so nullok",
			"auth        sufficient                                   pam_unix.so nullok\nauth        [default=die]                                pam_faillock.so authfail",
		},
		"already there, arguments set whole": {
			rockySystemAuth, Rule{Ref: ref("auth", "sufficient", "pam_unix.so"), Arguments: []string{}, State: Present},
			"auth        sufficient                                   pam_unix.so nullok",
			"auth        sufficient                                   pam_unix.so",
		},
		"already there, arguments left": {
			rockySystemAuth, Rule{Ref: ref("auth", "sufficient", "pam_unix.so"), State: Present, Before: "auth required pam_deny.so"}, "", "",
		},
		"args_present replaces a key and adds": {
			rockySystemAuth, Rule{Ref: ref("password", "sufficient", "pam_unix.so"), Arguments: []string{"remember=5", "yescrypt", "rounds=11"}, State: ArgsPresent},
			"password    sufficient                                   pam_unix.so yescrypt shadow nullok use_authtok",
			"password    sufficient                                   pam_unix.so yescrypt shadow nullok use_authtok remember=5 rounds=11",
		},
		"args_present changes a value": {
			rockySystemAuth, Rule{Ref: ref("auth", "required", "pam_faildelay.so"), Arguments: []string{"delay=4000000"}, State: ArgsPresent},
			"auth        required                                     pam_faildelay.so delay=2000000",
			"auth        required                                     pam_faildelay.so delay=4000000",
		},
		"args_absent drops nullok": {
			ubuntuCommonAuth, Rule{Ref: ref("auth", "[success=1 default=ignore]", "pam_unix.so"), Arguments: []string{"nullok"}, State: ArgsAbsent},
			"auth	[success=1 default=ignore]	pam_unix.so nullok",
			"auth	[success=1 default=ignore]	pam_unix.so",
		},
		"args_absent with nothing to drop": {
			ubuntuCommonAuth, Rule{Ref: ref("auth", "requisite", "pam_deny.so"), Arguments: []string{"nullok"}, State: ArgsAbsent}, "", "",
		},
		"args_absent on a missing rule": {
			ubuntuCommonAuth, Rule{Ref: faillock, Arguments: []string{"x"}, State: ArgsAbsent}, "", "",
		},
		"comment after the rule kept": {
			ubuntuSSHD, Rule{Ref: ref("session", "optional", "pam_mail.so"), Arguments: []string{"standard"}, State: Present},
			"session    optional     pam_mail.so standard noenv # [1]",
			"session    optional     pam_mail.so standard # [1]",
		},
		"absent": {
			rockySSHD, Rule{Ref: ref("session", "optional", "pam_keyinit.so"), State: Absent},
			"session    optional     pam_keyinit.so force revoke\n", "",
		},
		"absent, already gone": {
			rockySSHD, Rule{Ref: faillock, State: Absent}, "", "",
		},
		"replace in place": {
			rockySystemAuth, Rule{Ref: ref("auth", "requisite", "pam_deny.so"), State: Present, Replace: "auth required pam_deny.so"},
			"auth        required                                     pam_deny.so",
			"auth        requisite                                    pam_deny.so",
		},
		"-session is its own type": {
			rockySystemAuth, Rule{Ref: ref("-session", "optional", "pam_systemd.so"), Arguments: []string{"debug"}, State: Present},
			"-session    optional                                     pam_systemd.so",
			"-session    optional                                     pam_systemd.so debug",
		},
	} {
		t.Run(name, func(t *testing.T) {
			got, err := Apply(tc.in, tc.rule)
			if err != nil {
				t.Fatal(err)
			}
			want := tc.in
			if tc.old != "" {
				if !strings.Contains(want, tc.old) {
					t.Fatalf("fixture has no %q", tc.old)
				}
				want = strings.Replace(want, tc.old, tc.new, 1)
			}
			if got != want {
				t.Fatalf("got:\n%s\nwant:\n%s", got, want)
			}
			// The edit is in: applying it again changes nothing.
			if again, err := Apply(got, tc.rule); err != nil || again != got {
				t.Fatalf("second apply: %v\n%s", err, again)
			}
		})
	}
}

// Every rule matching the type, control and module changes, as with pamd.
func TestApplyEveryMatch(t *testing.T) {
	got, err := Apply(ubuntuSSHD, Rule{Ref: ref("session", "required", "pam_env.so"), Arguments: []string{"readenv=1"}, State: ArgsPresent})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, "session    required     pam_env.so readenv=1 # [1]\n") ||
		!strings.Contains(got, "pam_env.so user_readenv=1 envfile=/etc/default/locale readenv=1\n") {
		t.Fatal(got)
	}
}

func TestApplyLinesAndEnds(t *testing.T) {
	// A rule over two lines is read as one; edited, it's written on one.
	in := "auth required pam_env.so \\\n   readenv=1\nauth sufficient pam_unix.so\n"
	got, err := Apply(in, Rule{Ref: ref("auth", "required", "pam_env.so"), Arguments: []string{"readenv=0"}, State: ArgsPresent})
	if err != nil || got != "auth required pam_env.so readenv=0\nauth sufficient pam_unix.so\n" {
		t.Fatalf("continuation: %v %q", err, got)
	}
	if same, err := Apply(in, Rule{Ref: ref("auth", "required", "pam_env.so"), Arguments: []string{"readenv=1"}, State: ArgsPresent}); err != nil || same != in {
		t.Fatalf("continuation in sync: %v %q", err, same)
	}
	// A comment ends a line even after a backslash.
	in = "auth required pam_env.so # note \\\nauth sufficient pam_unix.so\n"
	if got, err := Apply(in, Rule{Ref: ref("auth", "sufficient", "pam_unix.so"), Arguments: []string{"nullok"}, State: Present}); err != nil || !strings.HasSuffix(got, "\nauth sufficient pam_unix.so nullok\n") {
		t.Fatalf("comment and backslash: %v %q", err, got)
	}
	// No newline at the end stays that way.
	in = "auth sufficient pam_unix.so\nauth required pam_deny.so"
	got, err = Apply(in, Rule{Ref: ref("auth", "required", "pam_faillock.so"), State: Present, After: "auth required pam_deny.so"})
	if err != nil || got != in+"\nauth required pam_faillock.so" {
		t.Fatalf("no final newline: %v %q", err, got)
	}
	// Bracketed arguments may hold spaces.
	in = "account required pam_access.so [listsep=, x]\n"
	if got, err := Apply(in, Rule{Ref: ref("account", "required", "pam_access.so"), Arguments: []string{"[listsep=, x]"}, State: Present}); err != nil || got != in {
		t.Fatalf("bracketed argument: %v %q", err, got)
	}
}

func TestApplyRefuses(t *testing.T) {
	for name, tc := range map[string]struct {
		in   string
		rule Rule
		want string
	}{
		"last auth rule": {
			"auth sufficient pam_unix.so\naccount required pam_unix.so\n",
			Rule{Ref: ref("auth", "sufficient", "pam_unix.so"), State: Absent}, "last auth rule",
		},
		"last auth rule, relabelled": {
			"auth sufficient pam_unix.so\n",
			Rule{Ref: ref("-auth", "sufficient", "pam_unix.so"), State: Present, Replace: "auth sufficient pam_unix.so"}, "last auth rule",
		},
		"no anchor given": {ubuntuCommonAuth, Rule{Ref: ref("auth", "required", "pam_faillock.so"), State: Present}, "set before or after"},
		"anchor missing": {
			ubuntuCommonAuth, Rule{Ref: ref("auth", "required", "pam_faillock.so"), State: Present, Before: "auth sufficient pam_unix.so"}, "nowhere to put",
		},
		"anchor twice": {
			ubuntuSSHD, Rule{Ref: ref("session", "required", "pam_limits.so"), State: Present, After: "session required pam_env.so"}, "more than one rule",
		},
		"nothing to replace": {
			ubuntuCommonAuth, Rule{Ref: ref("auth", "required", "pam_faillock.so"), State: Present, Replace: "auth required pam_tally2.so"}, "neither",
		},
		"args_present, no rule":  {ubuntuCommonAuth, Rule{Ref: ref("auth", "required", "pam_faillock.so"), Arguments: []string{"deny=3"}, State: ArgsPresent}, "no auth required pam_faillock.so rule"},
		"unknown type in file":   {"auht required pam_unix.so\n", Rule{Ref: ref("auth", "required", "pam_unix.so"), State: Absent}, "line 1 has type"},
		"short line in file":     {"auth required\n", Rule{Ref: ref("auth", "required", "pam_unix.so"), State: Absent}, "isn't a PAM rule"},
		"unclosed [ in the file": {"auth [success=1 pam_unix.so\n", Rule{Ref: ref("auth", "required", "pam_unix.so"), State: Absent}, "no ] to close"},
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := Apply(tc.in, tc.rule); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("error %v, want %q", err, tc.want)
			}
		})
	}
	// An auth rule may go while another stays.
	if _, err := Apply(rockySystemAuth, Rule{Ref: ref("auth", "required", "pam_env.so"), State: Absent}); err != nil {
		t.Fatal(err)
	}
}

func TestValidate(t *testing.T) {
	ok := Ref{"auth", "required", "pam_faillock.so"}
	for name, r := range map[string]Rule{
		"type":            {Ref: Ref{"auht", "required", "pam_x.so"}, State: Present},
		"control":         {Ref: Ref{"auth", "requried", "pam_x.so"}, State: Present},
		"definitive":      {Ref: Ref{"auth", "definitive", "pam_x.so"}, State: Present},
		"bracket value":   {Ref: Ref{"auth", "[sucess=1]", "pam_x.so"}, State: Present},
		"bracket action":  {Ref: Ref{"auth", "[success=jump]", "pam_x.so"}, State: Present},
		"zero jump":       {Ref: Ref{"auth", "[success=0]", "pam_x.so"}, State: Present},
		"empty brackets":  {Ref: Ref{"auth", "[ ]", "pam_x.so"}, State: Present},
		"module space":    {Ref: Ref{"auth", "required", "pam x.so"}, State: Present},
		"no module":       {Ref: Ref{"auth", "required", ""}, State: Present},
		"state":           {Ref: ok, State: "before"},
		"arg with #":      {Ref: ok, Arguments: []string{"a#b"}, State: Present},
		"arg with space":  {Ref: ok, Arguments: []string{"deny=3 unlock_time=60"}, State: Present},
		"arg backslash":   {Ref: ok, Arguments: []string{`x\`}, State: Present},
		"empty arg":       {Ref: ok, Arguments: []string{""}, State: Present},
		"both anchors":    {Ref: ok, State: Present, Before: "auth sufficient pam_unix.so", After: "auth required pam_deny.so"},
		"short anchor":    {Ref: ok, State: Present, Before: "auth pam_unix.so"},
		"anchor is self":  {Ref: ok, State: Present, Before: "auth required pam_faillock.so"},
		"anchor + absent": {Ref: ok, State: Absent, After: "auth required pam_deny.so"},
		"absent + args":   {Ref: ok, State: Absent, Arguments: []string{}},
		"args_present":    {Ref: ok, State: ArgsPresent},
		"args_absent":     {Ref: ok, State: ArgsAbsent, Arguments: []string{}},
		"bracket add":     {Ref: ok, State: ArgsPresent, Arguments: []string{"[a b]"}},
	} {
		if err := r.Validate(); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
	for _, r := range []Rule{
		{Ref: Ref{"-session", "[success=1 default=ignore]", "/lib64/security/pam_x.so"}, State: Present},
		{Ref: ok, State: Present, Arguments: []string{"[query=select 1]", "deny=3"}, Before: "auth [success=1 default=ignore] pam_unix.so"},
		{Ref: ok, State: Absent},
		{Ref: Ref{"password", "requisite", "pam_pwquality.so"}, State: ArgsPresent, Arguments: []string{"retry=3"}},
	} {
		if err := r.Validate(); err != nil {
			t.Errorf("%+v: %v", r, err)
		}
	}
}
